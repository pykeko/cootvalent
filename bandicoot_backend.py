# Self-test: a realistic multi-command session in ONE live coot process.
# Run:  python3 bandicoot_backend.py [PDB]
# ---------------------------------------------------------------------------

def _selftest(pdb_path):
    print("=" * 68)
    print("BandicootBackend self-test (fully headless, --no-graphics)")
    print("=" * 68)
    b = BandicootBackend()
    port = b.start()
    print("[start] server port=%d, coot pid=%d, banner OK"
          % (port, b._proc.pid))
    print("[start] DISPLAY env = %r (headless, no XQuartz)"
          % os.environ.get("DISPLAY"))

    try:
        # 1. load coordinates
        imol = b.load_coordinates(pdb_path)
        print("\n>>> load_coordinates(%s)" % pdb_path)
        print("    <<< imol = %r" % imol)

        # 2. atom count via write-back (n_atoms is unreliable headless)
        n_direct = b.eval('n_atoms(%d)' % imol)
        n_true = b.get_atom_count(imol)
        print("\n>>> n_atoms(%d)  [headless, unreliable]" % imol)
        print("    <<< %r" % n_direct)
        print(">>> get_atom_count(%d)  [write-back truth]" % imol)
        print("    <<< %r atoms" % n_true)

        # 3. set rotation centre and read it back
        print("\n>>> set_rotation_centre(11.0, 22.0, 33.0)")
        print("    <<< %r" % b.set_rotation_centre(11.0, 22.0, 33.0))
        rc = b.get_rotation_centre()
        print(">>> get_rotation_centre()")
        print("    <<< (%.3f, %.3f, %.3f)" % (rc[0], rc[1], rc[2]))

        # 4. go to residue
        print("\n>>> go_to_residue('A', 25)")
        print("    <<< status = %r" % b.go_to_residue("A", 25, imol=imol))

        # 5. LIVE MUTATION: residue_name before -> mutate -> residue_name after
        before = b.residue_name("A", 25, imol=imol)
        print("\n>>> residue_name('A', 25)  [before]")
        print("    <<< %r" % before)
        print(">>> mutate('A', 25, 'ALA')")
        print("    <<< status = %r" % b.mutate("A", 25, "ALA", imol=imol))
        after = b.residue_name("A", 25, imol=imol)
        print(">>> residue_name('A', 25)  [after]")
        print("    <<< %r" % after)
        mutation_ok = (before != after and after == "ALA")
        print("    ==> live mutation persisted: %s (%r -> %r)"
              % (mutation_ok, before, after))

        # 6. heartbeat
        print("\n>>> healthy()  [heartbeat 1+1==2]")
        print("    <<< %r" % b.healthy())

        # 7. latency: average over several tight round-trips
        N = 8
        t0 = time.time()
        for _ in range(N):
            b.eval("1+1")
        per = (time.time() - t0) / N * 1000.0
        print("\n>>> latency: %d x eval('1+1')" % N)
        print("    <<< ~%.1f ms / round-trip" % per)

        print("\n" + "=" * 68)
        print("RESULT: mutation_ok=%s  heartbeat=%s  latency=%.1fms  headless=%s"
              % (mutation_ok, b.healthy(), per, os.environ.get("DISPLAY") is None))
        print("=" * 68)
    finally:
        b.shutdown()
        print("[shutdown] '# close' sent, child terminated, sockets closed")


def main(argv):
    if "--integration-sketch" in argv:
        print(PYKEKOMCP_INTEGRATION)
        return 0
    default_pdb = os.path.expanduser(
        "~/xtal/lig_test/non_covalent/3PTB/3PTB.pdb")
    pdb = default_pdb
    for a in argv[1:]:
        if not a.startswith("-"):
            pdb = a
